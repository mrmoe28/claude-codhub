import SwiftUI
import SwiftData

struct IntegratedErrorFixerView: View {
    @Environment(\.modelContext) private var modelContext
    @Query private var knownErrors: [KnownError]
    
    @State private var errorText: String = ""
    @State private var generatedPrompt: String = ""
    @State private var suggestedSolutions: [KnownError] = []
    @State private var showingSuggestions = false
    
    @StateObject private var terminalManager = MultiTerminalManager()
    @StateObject private var automationManager = TerminalAutomationManager()
    
    @State private var showTerminals = false
    
    var body: some View {
        VStack(spacing: 0) {
            // Header with terminal integration
            HeaderView(
                terminalManager: terminalManager,
                automationManager: automationManager,
                showTerminals: $showTerminals
            )
            
            // Main content area - split view
            HSplitView {
                // Left side - Error input and suggestions
                VStack(alignment: .leading, spacing: 16) {
                    ErrorInputSection(
                        errorText: $errorText,
                        suggestedSolutions: $suggestedSolutions,
                        knownErrors: knownErrors
                    )
                    
                    if !suggestedSolutions.isEmpty {
                        SuggestionsSection(
                            suggestions: suggestedSolutions,
                            onApply: { solution in
                                generateEnhancedPrompt(with: solution)
                            }
                        )
                    }
                    
                    if !generatedPrompt.isEmpty {
                        GeneratedPromptSection(
                            prompt: generatedPrompt,
                            onSendToTerminals: {
                                sendPromptToTerminals()
                            }
                        )
                    }
                }
                .frame(minWidth: 400)
                .padding()
                
                // Right side - Terminal integration
                if showTerminals {
                    VStack(spacing: 0) {
                        // Terminal header
                        HStack {
                            Text("Claude Terminals")
                                .font(.headline)
                            
                            Spacer()
                            
                            if automationManager.isAutomating {
                                HStack {
                                    ProgressView()
                                        .controlSize(.small)
                                    Text(automationManager.automationStatus)
                                        .font(.caption)
                                        .foregroundColor(.secondary)
                                }
                            }
                            
                            Button("Hide Terminals") {
                                showTerminals = false
                            }
                            .buttonStyle(.bordered)
                            .controlSize(.small)
                        }
                        .padding()
                        .background(Color(NSColor.controlBackgroundColor))
                        
                        // Multi-terminal view
                        MultiTerminalView()
                            .environmentObject(terminalManager)
                            .environmentObject(automationManager)
                    }
                    .frame(minWidth: 500)
                }
            }
        }
        .onAppear {
            if knownErrors.isEmpty {
                ErrorKnowledgeDatabase.shared.populateDatabase(context: modelContext)
            }
        }
    }
    
    private func generateEnhancedPrompt(with solution: KnownError) {
        generatedPrompt = """
🔧 **Claude Code Enhanced Error Analysis Request**

I'm experiencing the following error and need your expert debugging assistance:

**Error Details:**
```
\(errorText)
```

**Knowledge Base Match Found:**
- **Error Type:** \(solution.category.rawValue)
- **Severity:** \(solution.severity.rawValue)
- **Known Title:** \(solution.title)

**Existing Solution Reference:**
\(solution.solution)

**Please provide:**
1. **🔍 Enhanced Root Cause Analysis**
2. **🌐 Advanced Research & Solutions**
3. **⚡ Customized Fix**
4. **💻 Complete Code Solution**
5. **🛡️ Enhanced Prevention Tips**

---
*Generated by Claude Code Hub Integrated Error Fixer*
"""
    }
    
    private func sendPromptToTerminals() {
        // Send the generated prompt to all active terminals
        for terminal in terminalManager.terminals {
            if terminal.isRunning && terminal.currentState == .claudeReady {
                terminal.sendCommand(generatedPrompt)
            }
        }
    }
}

struct HeaderView: View {
    @ObservedObject var terminalManager: MultiTerminalManager
    @ObservedObject var automationManager: TerminalAutomationManager
    @Binding var showTerminals: Bool
    
    var body: some View {
        HStack {
            Image(systemName: "exclamationmark.triangle.fill")
                .foregroundColor(.orange)
                .font(.title2)
            Text("Integrated Error Fixer with Terminals")
                .font(.title2)
                .fontWeight(.bold)
            
            Spacer()
            
            // Terminal control buttons
            HStack(spacing: 8) {
                Button("Show Terminals") {
                    showTerminals = true
                }
                .buttonStyle(.bordered)
                .disabled(showTerminals)
                
                Button("Start All Terminals") {
                    terminalManager.startAllTerminals()
                }
                .buttonStyle(.borderedProminent)
                .controlSize(.small)
                
                Button("Auto Claude Setup") {
                    Task {
                        await automationManager.runFullAutomation(for: terminalManager.terminals)
                    }
                }
                .buttonStyle(.borderedProminent)
                .controlSize(.small)
                .disabled(automationManager.isAutomating)
                
                Button("Test Desktop Commander") {
                    Task {
                        let response = await automationManager.testDesktopCommander()
                        print("Desktop Commander Test: \(response)")
                    }
                }
                .buttonStyle(.bordered)
                .controlSize(.small)
            }
        }
        .padding()
        .background(Color(NSColor.controlBackgroundColor))
    }
}

struct ErrorInputSection: View {
    @Binding var errorText: String
    @Binding var suggestedSolutions: [KnownError]
    let knownErrors: [KnownError]
    
    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            Text("Error Message Input")
                .font(.headline)
            
            TextEditor(text: $errorText)
                .font(.system(.body, design: .monospaced))
                .frame(minHeight: 120)
                .scrollContentBackground(.hidden)
                .background(Color(NSColor.textBackgroundColor))
                .cornerRadius(8)
                .overlay(
                    RoundedRectangle(cornerRadius: 8)
                        .stroke(Color.gray.opacity(0.3), lineWidth: 1)
                )
                .onChange(of: errorText) { _, _ in
                    findMatchingSolutions()
                }
            
            Text("Paste your error above - smart suggestions will appear automatically")
                .font(.caption)
                .foregroundColor(.secondary)
        }
    }
    
    private func findMatchingSolutions() {
        guard !errorText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            suggestedSolutions = []
            return
        }
        
        suggestedSolutions = knownErrors.filter { error in
            let searchTerms = errorText.lowercased()
            return error.errorMessage.lowercased().contains(searchTerms) ||
                   error.title.lowercased().contains(searchTerms) ||
                   error.tags.contains { $0.lowercased().contains(searchTerms) } ||
                   searchTerms.contains(error.errorMessage.lowercased()) ||
                   searchTerms.contains(error.title.lowercased())
        }.sorted { $0.severity.rawValue > $1.severity.rawValue }
    }
}

struct SuggestionsSection: View {
    let suggestions: [KnownError]
    let onApply: (KnownError) -> Void
    
    var body: some View {
        VStack(alignment: .leading, spacing: 8) {
            Text("💡 Smart Suggestions (\(suggestions.count) found)")
                .font(.headline)
                .foregroundColor(.accentColor)
            
            ScrollView(.horizontal, showsIndicators: false) {
                HStack(spacing: 12) {
                    ForEach(suggestions.prefix(3), id: \.id) { suggestion in
                        SuggestionCard(solution: suggestion) {
                            onApply(suggestion)
                        }
                    }
                }
                .padding(.horizontal, 4)
            }
        }
    }
}

struct GeneratedPromptSection: View {
    let prompt: String
    let onSendToTerminals: () -> Void
    
    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack {
                Text("Generated Claude Prompt")
                    .font(.headline)
                
                Spacer()
                
                Button("Copy Prompt") {
                    NSPasteboard.general.clearContents()
                    NSPasteboard.general.setString(prompt, forType: .string)
                }
                .buttonStyle(.bordered)
                .controlSize(.small)
                
                Button("Send to Terminals") {
                    onSendToTerminals()
                }
                .buttonStyle(.borderedProminent)
                .controlSize(.small)
            }
            
            ScrollView {
                Text(prompt)
                    .textSelection(.enabled)
                    .padding()
                    .background(Color(NSColor.textBackgroundColor))
                    .cornerRadius(8)
            }
            .frame(maxHeight: 200)
        }
    }
}

